-- StockWise Oracle star schema
-- Oracle Database 12c+ (identity columns are used for surrogate dimension keys).
-- Run this script in a dedicated project schema. Drop existing tables manually
-- in reverse dependency order before re-running.

CREATE TABLE dim_supplier (
    supplier_key    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    supplier_id     VARCHAR2(20)  NOT NULL,
    supplier_name   VARCHAR2(100) NOT NULL,
    region          VARCHAR2(40),
    rating          NUMBER(2,1),
    CONSTRAINT pk_dim_supplier PRIMARY KEY (supplier_key),
    CONSTRAINT uq_dim_supplier_id UNIQUE (supplier_id),
    CONSTRAINT ck_dim_supplier_rating CHECK (rating IS NULL OR rating BETWEEN 0 AND 5)
);

CREATE TABLE dim_product (
    product_key     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    product_id      VARCHAR2(20)  NOT NULL,
    sku             VARCHAR2(30)  NOT NULL,
    product_name    VARCHAR2(120) NOT NULL,
    category        VARCHAR2(60)  NOT NULL,
    unit_cost       NUMBER(12,2)  NOT NULL,
    reorder_level   NUMBER(10)    NOT NULL,
    CONSTRAINT pk_dim_product PRIMARY KEY (product_key),
    CONSTRAINT uq_dim_product_id UNIQUE (product_id),
    CONSTRAINT uq_dim_product_sku UNIQUE (sku),
    CONSTRAINT ck_dim_product_cost CHECK (unit_cost >= 0),
    CONSTRAINT ck_dim_product_reorder CHECK (reorder_level >= 0)
);

CREATE TABLE dim_date (
    date_key        NUMBER(8)     NOT NULL,
    full_date       DATE          NOT NULL,
    calendar_year   NUMBER(4)     NOT NULL,
    calendar_quarter NUMBER(1)    NOT NULL,
    calendar_month  NUMBER(2)     NOT NULL,
    month_name      VARCHAR2(15)  NOT NULL,
    day_of_month    NUMBER(2)     NOT NULL,
    weekday_name    VARCHAR2(12)  NOT NULL,
    CONSTRAINT pk_dim_date PRIMARY KEY (date_key),
    CONSTRAINT uq_dim_date_full_date UNIQUE (full_date),
    CONSTRAINT ck_dim_date_key CHECK (date_key BETWEEN 19000101 AND 29991231),
    CONSTRAINT ck_dim_date_quarter CHECK (calendar_quarter BETWEEN 1 AND 4),
    CONSTRAINT ck_dim_date_month CHECK (calendar_month BETWEEN 1 AND 12),
    CONSTRAINT ck_dim_date_day CHECK (day_of_month BETWEEN 1 AND 31)
);

CREATE TABLE fact_inventory (
    inventory_id        VARCHAR2(20) NOT NULL,
    product_key         NUMBER       NOT NULL,
    snapshot_date_key   NUMBER(8)    NOT NULL,
    opening_quantity    NUMBER(12)   NOT NULL,
    received_quantity   NUMBER(12)   NOT NULL,
    issued_quantity     NUMBER(12)   NOT NULL,
    reserved_quantity   NUMBER(12)   NOT NULL,
    available_quantity  NUMBER(12)   NOT NULL,
    CONSTRAINT pk_fact_inventory PRIMARY KEY (inventory_id),
    CONSTRAINT fk_inv_product FOREIGN KEY (product_key) REFERENCES dim_product(product_key),
    CONSTRAINT fk_inv_date FOREIGN KEY (snapshot_date_key) REFERENCES dim_date(date_key),
    CONSTRAINT ck_inv_opening CHECK (opening_quantity >= 0),
    CONSTRAINT ck_inv_received CHECK (received_quantity >= 0),
    CONSTRAINT ck_inv_issued CHECK (issued_quantity >= 0),
    CONSTRAINT ck_inv_reserved CHECK (reserved_quantity >= 0)
);

CREATE TABLE fact_stock_movement (
    movement_id       VARCHAR2(20) NOT NULL,
    product_key       NUMBER       NOT NULL,
    movement_date_key NUMBER(8)    NOT NULL,
    movement_type     VARCHAR2(3)  NOT NULL,
    quantity          NUMBER(12)   NOT NULL,
    reference         VARCHAR2(40),
    CONSTRAINT pk_fact_stock_movement PRIMARY KEY (movement_id),
    CONSTRAINT fk_move_product FOREIGN KEY (product_key) REFERENCES dim_product(product_key),
    CONSTRAINT fk_move_date FOREIGN KEY (movement_date_key) REFERENCES dim_date(date_key),
    CONSTRAINT ck_move_type CHECK (movement_type IN ('IN', 'OUT')),
    CONSTRAINT ck_move_quantity CHECK (quantity > 0)
);

CREATE TABLE fact_purchase_order (
    order_id                  VARCHAR2(20) NOT NULL,
    product_key               NUMBER       NOT NULL,
    supplier_key              NUMBER       NOT NULL,
    order_date_key            NUMBER(8)    NOT NULL,
    expected_delivery_date_key NUMBER(8)   NOT NULL,
    actual_delivery_date_key  NUMBER(8),
    quantity_ordered          NUMBER(12)   NOT NULL,
    unit_cost                 NUMBER(12,2) NOT NULL,
    CONSTRAINT pk_fact_purchase_order PRIMARY KEY (order_id),
    CONSTRAINT fk_po_product FOREIGN KEY (product_key) REFERENCES dim_product(product_key),
    CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_key) REFERENCES dim_supplier(supplier_key),
    CONSTRAINT fk_po_order_date FOREIGN KEY (order_date_key) REFERENCES dim_date(date_key),
    CONSTRAINT fk_po_expected_date FOREIGN KEY (expected_delivery_date_key) REFERENCES dim_date(date_key),
    CONSTRAINT fk_po_actual_date FOREIGN KEY (actual_delivery_date_key) REFERENCES dim_date(date_key),
    CONSTRAINT ck_po_quantity CHECK (quantity_ordered > 0),
    CONSTRAINT ck_po_unit_cost CHECK (unit_cost >= 0)
);

-- Helpful indexes for common filtering and join paths.
CREATE INDEX ix_fact_inventory_product ON fact_inventory(product_key);
CREATE INDEX ix_fact_inventory_date ON fact_inventory(snapshot_date_key);
CREATE INDEX ix_fact_movement_product ON fact_stock_movement(product_key);
CREATE INDEX ix_fact_movement_date ON fact_stock_movement(movement_date_key);
CREATE INDEX ix_fact_po_product ON fact_purchase_order(product_key);
CREATE INDEX ix_fact_po_supplier ON fact_purchase_order(supplier_key);
CREATE INDEX ix_fact_po_order_date ON fact_purchase_order(order_date_key);
